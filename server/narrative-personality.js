const STEM_EL = [0,0,1,1,2,2,3,3,4,4];
const fill = (t, v) => t.replace(/\{(\w+)\}/g, (_, k) => v[k] ?? "");

/* ch: 기존 buildChart 결과. sign(), natalGroups()는 worker.js 안의 함수를 그대로 쓴다고 가정. */
export function personalityChapter(ch, { sign, natalGroups, ZOD }) {
  const cnt = ch.cnt, dom = cnt.indexOf(Math.max(...cnt));
  const lack = cnt.indexOf(Math.min(...cnt));
  const moonEl = sign(ch.moon) % 4;               // 0불 1흙 2공기 3물
  const ng = natalGroups(ch), top = ng.indexOf(Math.max(...ng));
  const v = { name: ch.inp.name || "당신" };
  return {
    title: "타고난 성격과 기질",
    paragraphs: [
      fill(INTRO[ch.stems.d], v),
      fill(SCENE[dom], v),
      fill(FEEL[moonEl], v),
      fill(LIGHT[top][ch.strong ? 0 : 1], v),
      fill(ACT[lack], v)
    ],
    /* 본문에서 뺀 근거: 접기 박스용 */
    basis: [
      "일간 " + "갑을병정무기경신임계"[ch.stems.d],
      "가장 많은 오행 " + "목화토금수"[dom] + " " + cnt[dom] + "개",
      "가장 적은 오행 " + "목화토금수"[lack],
      "달 " + ZOD[sign(ch.moon)] + "자리",
      (ch.strong ? "신강" : "신약") + " · 많은 십성 " + ["비겁","식상","재성","관성","인성"][top]
    ]
  };
}
